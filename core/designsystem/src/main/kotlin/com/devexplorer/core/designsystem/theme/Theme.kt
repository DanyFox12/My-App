/**
 * The single theme wrapper for the whole app.
 *
 * Behavior:
 *  - **Dynamic color (Material You)** is used on Android 12+ (API 31) when
 *    [dynamicColor] is on, so the app blends with the user's wallpaper.
 *  - On older phones it transparently falls back to the curated brand palette.
 *    This is the pattern that keeps one codebase beautiful on new phones and
 *    correct on old ones — the version check is the only branch.
 *  - It also resolves the device [com.devexplorer.core.model.PerformanceBudget]
 *    once and provides it to the tree via [LocalPerformanceBudget].
 *
 * @param dynamicColor user preference; defaults on. Ignored below API 31.
 */
@Composable
fun DevExplorerTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    dynamicColor: Boolean = true,
    content: @Composable () -> Unit,
) {
    val context = LocalContext.current

    val colorScheme = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
            if (darkTheme) dynamicDarkColorScheme(context)
            else dynamicLightColorScheme(context)
        }
        darkTheme -> DarkColors
        else -> LightColors
    }

    // Detect device capability once and remember it for the whole composition.
    val budget = remember(context) { DeviceCapabilities.detect(context).budget }

    CompositionLocalProvider(LocalPerformanceBudget provides budget) {
        MaterialTheme(
            colorScheme = colorScheme,
            typography = DevExplorerTypography,
            content = content,
        )
    }
}
